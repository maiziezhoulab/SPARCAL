#!/usr/bin/env python3
"""Build one collision-safe, self-contained P4/P6 SPARCALViewer study.

This is the generic packaging stage used by ``run_spatial_to_viewer.py``.  The
study name always includes an explicit run label, and an existing study is an
error unless ``--overwrite`` is supplied.  The package also carries the
spatial-filter summary and mechanistic VAF table as provenance sidecars.
"""

from __future__ import annotations

import argparse
import gzip
import hashlib
import json
import re
import shutil
import sys
import tempfile
import zipfile
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.io import mmread


PROJECT_ROOT = Path("/data/maiziezhou_lab/leiy4/snv_calling")
STMUT_ROOT = Path(
    "/lfs/archer.accre.vu/maiziezhou_lab/maiziezhou_lab/"
    "Datasets/ST_datasets/STmut_Data"
)
POSITION_COLUMNS = [
    "barcode", "in_tissue", "array_row", "array_col",
    "pxl_row_in_fullres", "pxl_col_in_fullres",
]


def safe_token(value: str, label: str) -> str:
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_.-]*", value):
        raise ValueError(f"{label} must contain only letters, numbers, '.', '_' or '-': {value!r}")
    return value


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def spatial_inputs(dataset: str, section_id: str) -> dict[str, Path]:
    cohort = dataset.split("_")[0]
    outs = (
        STMUT_ROOT / f"{cohort}_Visium" / f"spaceranger_align_rep{section_id}_hg19"
        / f"{cohort}_Tumor_output" / "outs"
    )
    spatial = outs / "spatial"
    return {
        "outs": outs,
        "positions": spatial / "tissue_positions.csv",
        "image": spatial / "tissue_hires_image.png",
        "scalefactors": spatial / "scalefactors_json.json",
    }


def normalize_positions(source: Path, destination: Path) -> pd.DataFrame:
    with source.open() as handle:
        first_line = handle.readline().strip()
    if first_line.startswith("barcode,"):
        frame = pd.read_csv(source)
    else:
        frame = pd.read_csv(source, header=None, names=POSITION_COLUMNS)
    missing = set(POSITION_COLUMNS) - set(frame.columns)
    if missing:
        raise ValueError(f"Missing position columns in {source}: {sorted(missing)}")
    frame = frame[POSITION_COLUMNS].copy()
    frame["barcode"] = frame["barcode"].astype(str)
    frame.to_csv(destination, index=False)
    return frame


def total_umi_per_spot(outs: Path) -> pd.DataFrame:
    matrix_dir = outs / "filtered_feature_bc_matrix"
    barcode_path = matrix_dir / "barcodes.tsv.gz"
    if not barcode_path.is_file():
        barcode_path = matrix_dir / "barcodes.tsv"
    matrix_path = matrix_dir / "matrix.mtx.gz"
    if not matrix_path.is_file():
        matrix_path = matrix_dir / "matrix.mtx"
    if not barcode_path.is_file() or not matrix_path.is_file():
        raise FileNotFoundError(f"Missing filtered Matrix Market input under {matrix_dir}")
    opener = gzip.open if barcode_path.suffix == ".gz" else open
    with opener(barcode_path, "rt") as handle:
        barcodes = [line.strip() for line in handle if line.strip()]
    totals = np.asarray(mmread(matrix_path).tocsc().sum(axis=0)).ravel().astype(np.int64)
    if len(barcodes) != len(totals):
        raise ValueError(f"Barcode/matrix mismatch in {matrix_dir}")
    return pd.DataFrame({"barcode": barcodes, "total_umi": totals})


def viewer_config(study_name: str) -> str:
    return f"""# SPARCALViewer study generated by the spatial-to-viewer pipeline
project: SPARCAL
study: {study_name}
genome: hg19

files:
  snv_matrix: snv_matrix.pkl
  tissue_positions: tissue_positions.csv
  hires_image: tissue_hires_image.png
  scalefactors: scalefactors_json.json
  tumor_groups: tumor_groups.csv
  variant_groups: variant_groups.csv
  tumor_centers: tumor_centers.csv
  spot_coverage: spot_coverage.csv

image:
  x_column: pxl_col_in_fullres
  y_column: pxl_row_in_fullres
  scalef_key: tissue_hires_scalef
  spot_diameter_key: spot_diameter_fullres
  in_tissue_only: true

variant_grouping:
  general_min_fraction: 80
  exclusive_inside_min: 80
  exclusive_outside_max: 20
"""


def build_package(args: argparse.Namespace) -> dict[str, object]:
    dataset = args.dataset.upper()
    cohort = dataset.split("_")[0]
    run_label = safe_token(args.run_label, "run label")
    model = safe_token(args.model, "model")
    matrix_class = safe_token(args.matrix_class, "matrix class")
    study_name = f"{cohort}_rep{args.section_id}_SPARCAL_{matrix_class}_{run_label}"
    section_root = args.section_root.resolve()
    matrix_path = (
        section_root / "matrix"
        / f"{dataset}_{args.section_id}_{model}_{matrix_class}_matrix.pkl"
    )
    sf_root = section_root / "spatial_filter_purity" / args.quality_filter
    spatial = spatial_inputs(dataset, args.section_id)
    required = [matrix_path, spatial["positions"], spatial["image"], spatial["scalefactors"]]
    missing = [str(path) for path in required if not path.is_file()]
    if missing:
        raise FileNotFoundError("Missing viewer input(s):\n  " + "\n  ".join(missing))

    args.output_root.mkdir(parents=True, exist_ok=True)
    package_dir = args.output_root / study_name
    archive_path = args.output_root / f"{study_name}.zip"
    if package_dir.exists() or archive_path.exists():
        if not args.overwrite:
            raise FileExistsError(
                f"Viewer study already exists: {package_dir}. Use a new --run-label "
                "or pass --overwrite explicitly."
            )
        if package_dir.exists():
            shutil.rmtree(package_dir)
        archive_path.unlink(missing_ok=True)

    with tempfile.TemporaryDirectory(prefix=f".{study_name}.", dir=args.output_root) as temp_dir:
        stage = Path(temp_dir) / study_name
        stage.mkdir()
        matrix = pd.read_pickle(matrix_path)
        if matrix.empty:
            raise ValueError(f"Empty SPARCAL matrix: {matrix_path}")
        if matrix.index.has_duplicates or matrix.columns.has_duplicates:
            raise ValueError(f"Duplicate matrix labels in {matrix_path}")
        matrix = (matrix > 0).astype(np.uint8)
        matrix.index = matrix.index.astype(str)
        matrix.columns = matrix.columns.astype(str)
        matrix.to_pickle(stage / "snv_matrix.pkl")

        positions = normalize_positions(spatial["positions"], stage / "tissue_positions.csv")
        shutil.copy2(spatial["image"], stage / "tissue_hires_image.png")
        shutil.copy2(spatial["scalefactors"], stage / "scalefactors_json.json")
        coverage = total_umi_per_spot(spatial["outs"])
        coverage.to_csv(stage / "spot_coverage.csv", index=False)
        pd.DataFrame(columns=["profile", "region_name", "barcode"]).to_csv(
            stage / "tumor_groups.csv", index=False
        )
        pd.DataFrame(
            columns=["profile", "region_name", "group_name", "group_type", "snv_key"]
        ).to_csv(stage / "variant_groups.csv", index=False)
        pd.DataFrame(columns=["profile", "region_name", "barcode"]).to_csv(
            stage / "tumor_centers.csv", index=False
        )
        (stage / f"{study_name}.config").write_text(viewer_config(study_name))

        evidence_files = []
        for name in ("spatial_filter_summary.txt", "all_variant_scores.txt", "mechanistic_vaf_scores.tsv"):
            source = sf_root / name
            if source.is_file():
                destination = stage / "evidence" / name
                destination.parent.mkdir(exist_ok=True)
                shutil.copy2(source, destination)
                evidence_files.append(f"evidence/{name}")

        position_barcodes = set(positions.loc[positions["in_tissue"] == 1, "barcode"])
        coverage_barcodes = set(coverage["barcode"].astype(str))
        matrix_barcodes = set(matrix.index)
        qc = {
            "matrix_spots": int(matrix.shape[0]),
            "matrix_snvs": int(matrix.shape[1]),
            "matrix_dtype": str(matrix.dtypes.iloc[0]),
            "matrix_barcodes_in_tissue": int(len(matrix_barcodes & position_barcodes)),
            "matrix_barcodes_with_coverage": int(len(matrix_barcodes & coverage_barcodes)),
            "matrix_barcodes_missing_positions": sorted(matrix_barcodes - position_barcodes),
            "matrix_barcodes_missing_coverage": sorted(matrix_barcodes - coverage_barcodes),
        }
        if qc["matrix_barcodes_missing_positions"]:
            raise ValueError("Matrix contains barcodes absent from in-tissue positions")
        (stage / "viewer_qc.json").write_text(json.dumps(qc, indent=2) + "\n")

        manifest = {
            "study": study_name,
            "dataset": dataset,
            "section_id": str(args.section_id),
            "run_label": run_label,
            "matrix_class": matrix_class,
            "matrix_source": str(matrix_path),
            "spatial_filter_source": str(sf_root),
            "matrix_shape": [int(matrix.shape[0]), int(matrix.shape[1])],
            "evidence_files": evidence_files,
            "collision_policy": "unique run label; fail unless --overwrite",
        }
        (stage / "MANIFEST.json").write_text(json.dumps(manifest, indent=2) + "\n")

        package_files = sorted(path for path in stage.rglob("*") if path.is_file())
        with zipfile.ZipFile(
            archive_path, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=6
        ) as archive:
            for path in package_files:
                archive.write(path, arcname=f"{study_name}/{path.relative_to(stage)}")
        stage.rename(package_dir)

    result = {
        "study": study_name,
        "package_dir": str(package_dir),
        "config": str(package_dir / f"{study_name}.config"),
        "archive": str(archive_path),
        "archive_bytes": archive_path.stat().st_size,
        "archive_sha256": sha256(archive_path),
        "spots": int(matrix.shape[0]),
        "snvs": int(matrix.shape[1]),
    }
    print(json.dumps(result, indent=2))
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dataset", required=True, choices=["P4_TUMOR", "P6_TUMOR"])
    parser.add_argument("--section-id", required=True, choices=["1", "2"])
    parser.add_argument("--section-root", required=True, type=Path)
    parser.add_argument("--quality-filter", default="baseQ0mapQ0")
    parser.add_argument("--model", required=True)
    parser.add_argument("--matrix-class", default="somatic",
                        choices=["1000G", "UPV", "germline", "somatic", "merged"])
    parser.add_argument("--run-label", required=True)
    parser.add_argument("--output-root", required=True, type=Path)
    parser.add_argument("--overwrite", action="store_true")
    args = parser.parse_args()
    build_package(args)
    return 0


if __name__ == "__main__":
    sys.exit(main())
