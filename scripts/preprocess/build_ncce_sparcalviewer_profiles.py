#!/usr/bin/env python3
"""Build self-contained SPARCALViewer study packages for the NCCE cohort.

Every generated file is placed under ``data/ncce/viewer_profiles``.  The
SpaceRanger outputs and the original cell-type/copyKAT annotations are read
only; no source dataset file is changed.  Each package contains the merged
SPARCAL matrix, Visium spatial assets, coverage-normalization data, and two
preloaded viewer profiles:

* ``CopyKAT``: Tumor (aneuploid) and Normal (diploid) spot groups.
* ``Cell types``: one region for every supplied cell-type annotation.

The resulting ``release_assets/NCCE_<sample>_SPARCAL.zip`` files can be
uploaded directly to the SpatialOmicViewer study-data release.
"""

from __future__ import annotations

import argparse
import gzip
import hashlib
import json
import shutil
import sys
import zipfile
from pathlib import Path
from typing import Dict, Iterable, List

import numpy as np
import pandas as pd
from scipy.io import mmread


PROJECT_ROOT = Path("/data/maiziezhou_lab/leiy4/snv_calling")
SPACERANGER_ROOT = Path("/data/maiziezhou_lab/Weiman/ST_CNV/data/spaceranger_outs")
SAMPLES = ["6A", "6B", "6C", "8A", "8B", "8C", "10A", "10B", "10C", "11A", "11B", "11C", "14A", "14B", "14C"]
SPATIAL_FILES = ("tissue_positions.csv", "tissue_hires_image.png", "scalefactors_json.json")


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def total_umi_per_spot(outs_dir: Path) -> pd.DataFrame:
    """Read per-spot total UMIs from the filtered SpaceRanger MTX matrix.

    The project Conda environment includes SciPy but not h5py, so use the
    equivalent Matrix Market representation rather than the H5 convenience
    file.  Both are read-only source inputs.
    """
    matrix_dir = outs_dir / "filtered_feature_bc_matrix"
    barcode_path = matrix_dir / "barcodes.tsv.gz"
    if not barcode_path.is_file():
        barcode_path = matrix_dir / "barcodes.tsv"
    matrix_path = matrix_dir / "matrix.mtx.gz"
    if not matrix_path.is_file():
        matrix_path = matrix_dir / "matrix.mtx"
    if not barcode_path.is_file() or not matrix_path.is_file():
        raise FileNotFoundError(
            f"Missing filtered Matrix Market input under {matrix_dir}"
        )

    opener = gzip.open if barcode_path.suffix == ".gz" else open
    with opener(barcode_path, "rt") as handle:
        barcodes = [line.strip() for line in handle if line.strip()]
    matrix = mmread(matrix_path).tocsc()
    totals = np.asarray(matrix.sum(axis=0)).ravel().astype(np.int64)
    if len(barcodes) != len(totals):
        raise ValueError(
            f"Barcode / matrix-column mismatch in {matrix_dir}: "
            f"{len(barcodes)} != {len(totals)}"
        )
    return pd.DataFrame({"barcode": barcodes, "total_umi": totals})


def viewer_config(study_name: str) -> str:
    return f"""# SPARCALViewer study package generated by SPARCAL
project: SPARCAL
study: {study_name}
genome: GRCh38

files:
  snv_matrix: snv_matrix.pkl
  tissue_positions: tissue_positions.csv
  hires_image: tissue_hires_image.png
  scalefactors: scalefactors_json.json
  tumor_groups: tumor_groups.csv
  variant_groups: variant_groups.csv
  tumor_centers: tumor_centers.csv
  spot_coverage: spot_coverage.csv

image:
  x_column: pxl_col_in_fullres
  y_column: pxl_row_in_fullres
  scalef_key: tissue_hires_scalef
  spot_diameter_key: spot_diameter_fullres
  in_tissue_only: true

variant_grouping:
  general_min_fraction: 80
  exclusive_inside_min: 80
  exclusive_outside_max: 20
"""


def make_tumor_groups(metadata: pd.DataFrame, matrix_barcodes: Iterable[str]) -> pd.DataFrame:
    """Convert project-local annotations into the viewer's profile CSV schema."""
    keep = set(map(str, matrix_barcodes))
    annotation = metadata.copy()
    annotation["barcode"] = annotation["barcode"].astype(str)
    annotation = annotation[annotation["barcode"].isin(keep)]
    rows: List[tuple] = []

    if "Tumor" in annotation.columns:
        assigned = set()
        for record in annotation[["barcode", "Tumor"]].dropna().itertuples(index=False):
            tumor = float(record.Tumor)
            region = "Tumor" if tumor >= 0.5 else "Normal"
            rows.append(("CopyKAT", region, record.barcode))
            assigned.add(record.barcode)
        # Some sections have copyKAT predictions only for a subset of in-tissue
        # spots.  Preserve that fact explicitly instead of silently excluding
        # those rows from a profile comparison.
        rows.extend(("CopyKAT", "Unassigned", barcode) for barcode in sorted(keep - assigned))

    if "cell_type" in annotation.columns:
        assigned = set()
        for record in annotation[["barcode", "cell_type"]].dropna().itertuples(index=False):
            cell_type = str(record.cell_type).strip()
            if cell_type:
                rows.append(("Cell types", cell_type, record.barcode))
                assigned.add(record.barcode)
        rows.extend(("Cell types", "Unassigned", barcode) for barcode in sorted(keep - assigned))

    return pd.DataFrame(rows, columns=["profile", "region_name", "barcode"])


def package_sample(sample: str, output_root: Path) -> Dict[str, object]:
    section_root = PROJECT_ROOT / "data" / "ncce" / sample
    matrix_path = section_root / "matrix" / f"NCCE_{sample}_SPARCAL_merged_matrix.pkl"
    metadata_path = section_root / "annotations" / "spot_metadata.tsv"
    outs_dir = SPACERANGER_ROOT / f"NCCE_{sample}" / "outs"
    spatial_dir = outs_dir / "spatial"
    study_name = f"NCCE_{sample}_SPARCAL"
    package_dir = output_root / study_name

    missing = [str(path) for path in (matrix_path, metadata_path) if not path.is_file()]
    missing.extend(str(spatial_dir / name) for name in SPATIAL_FILES if not (spatial_dir / name).is_file())
    if missing:
        raise FileNotFoundError("Required NCCE viewer inputs are missing:\n  " + "\n  ".join(missing))

    package_dir.mkdir(parents=True, exist_ok=True)
    matrix = pd.read_pickle(matrix_path)
    if matrix.empty:
        raise ValueError(f"Merged SPARCAL matrix is empty: {matrix_path}")
    matrix = matrix.copy()
    matrix.index = matrix.index.astype(str)
    matrix.columns = matrix.columns.astype(str)
    matrix = (matrix > 0).astype(np.uint8)
    matrix.to_pickle(package_dir / "snv_matrix.pkl")

    for filename in SPATIAL_FILES:
        shutil.copy2(spatial_dir / filename, package_dir / filename)

    coverage = total_umi_per_spot(outs_dir)
    coverage.to_csv(package_dir / "spot_coverage.csv", index=False)

    metadata = pd.read_csv(metadata_path, sep="\t", dtype={"barcode": str})
    tumor_groups = make_tumor_groups(metadata, matrix.index)
    tumor_groups.to_csv(package_dir / "tumor_groups.csv", index=False)
    pd.DataFrame(columns=["profile", "region_name", "group_name", "group_type", "snv_key"]).to_csv(
        package_dir / "variant_groups.csv", index=False
    )
    pd.DataFrame(columns=["profile", "region_name", "barcode"]).to_csv(
        package_dir / "tumor_centers.csv", index=False
    )
    (package_dir / f"{study_name}.config").write_text(viewer_config(study_name))

    copykat_rows = tumor_groups[tumor_groups["profile"] == "CopyKAT"]
    celltype_rows = tumor_groups[tumor_groups["profile"] == "Cell types"]
    package_manifest = {
        "study": study_name,
        "matrix_source": f"data/ncce/{sample}/matrix/{matrix_path.name}",
        "matrix_class": "merged",
        "matrix_shape": [int(matrix.shape[0]), int(matrix.shape[1])],
        "matrix_dtype": str(matrix.dtypes.iloc[0]),
        "copykat_tumor_spots": int((copykat_rows["region_name"] == "Tumor").sum()),
        "copykat_normal_spots": int((copykat_rows["region_name"] == "Normal").sum()),
        "copykat_unassigned_spots": int((copykat_rows["region_name"] == "Unassigned").sum()),
        "cell_type_regions": int(celltype_rows["region_name"].nunique()),
        "source_data_read_only": True,
    }
    (package_dir / "MANIFEST.json").write_text(json.dumps(package_manifest, indent=2) + "\n")

    # Zip exactly the published package contents.  This avoids accidentally
    # including any locally created viewer state on repeated builds.
    release_dir = output_root / "release_assets"
    release_dir.mkdir(parents=True, exist_ok=True)
    archive_path = release_dir / f"{study_name}.zip"
    package_files = [
        package_dir / "snv_matrix.pkl",
        *(package_dir / name for name in SPATIAL_FILES),
        package_dir / "spot_coverage.csv",
        package_dir / "tumor_groups.csv",
        package_dir / "variant_groups.csv",
        package_dir / "tumor_centers.csv",
        package_dir / f"{study_name}.config",
        package_dir / "MANIFEST.json",
    ]
    with zipfile.ZipFile(archive_path, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=6) as archive:
        for path in package_files:
            archive.write(path, arcname=f"{study_name}/{path.name}")

    return {
        "sample": sample,
        "study": study_name,
        "spots": int(matrix.shape[0]),
        "snvs": int(matrix.shape[1]),
        "copykat_tumor_spots": package_manifest["copykat_tumor_spots"],
        "copykat_normal_spots": package_manifest["copykat_normal_spots"],
        "cell_type_regions": package_manifest["cell_type_regions"],
        "archive": archive_path.name,
        "archive_bytes": archive_path.stat().st_size,
        "archive_sha256": sha256(archive_path),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--samples", nargs="+", default=SAMPLES,
                        help="NCCE sample IDs to package (default: all 15)")
    parser.add_argument("--output-root", type=Path,
                        default=PROJECT_ROOT / "data" / "ncce" / "viewer_profiles",
                        help="Project-local output directory for packages and release assets")
    args = parser.parse_args()

    unknown = sorted(set(args.samples) - set(SAMPLES))
    if unknown:
        parser.error(f"Unknown NCCE sample(s): {', '.join(unknown)}")

    args.output_root.mkdir(parents=True, exist_ok=True)
    results = []
    for sample in args.samples:
        print(f"Building SPARCALViewer package for NCCE {sample}...", flush=True)
        results.append(package_sample(sample, args.output_root))

    manifest = pd.DataFrame(results)
    manifest_path = args.output_root / "release_assets" / "NCCE_SPARCALViewer_manifest.tsv"
    manifest.to_csv(manifest_path, sep="\t", index=False)
    print(f"\nBuilt {len(results)} self-contained study packages.")
    print(f"Release assets: {args.output_root / 'release_assets'}")
    print(f"Manifest: {manifest_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
